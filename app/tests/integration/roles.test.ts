// What synapse_app may do once migrate.sh has run: DML on the app's tables, read-only on users,
// and no DDL (AC6). Each statement runs in a transaction that's rolled back, so a grant that's
// too wide fails the test without changing the database.

import { DatabaseError } from "pg";
import { describe, expect, it } from "vitest";

import { appRole, superuser, withClient } from "@/tests/support/pg";

const DATABASE = "synapse_test";

async function asApp(statement: string) {
  return withClient(appRole(process.env, DATABASE), async (client) => {
    await client.query("BEGIN");
    try {
      return await client.query(statement);
    } finally {
      await client.query("ROLLBACK");
    }
  });
}

describe("synapse_app", () => {
  it.each([
    ["create a table", "CREATE TABLE intruder (id int)"],
    ["create a schema", "CREATE SCHEMA intruder"],
    ["alter users", "ALTER TABLE users ADD COLUMN intruder int"],
    ["drop users", "DROP TABLE users"],
    ["truncate users", "TRUNCATE users"],
    ["insert into users", "INSERT INTO users (username, password_hash) VALUES ('intruder', 'x')"],
    ["update users", "UPDATE users SET username = username"],
    ["delete from users", "DELETE FROM users"],
    ["read the migration ledger", "SELECT * FROM drizzle.__drizzle_migrations"],
  ])("can't %s", async (_, statement) => {
    const error = await asApp(statement).then(
      () => undefined,
      (caught: unknown) => caught,
    );

    expect(error).toBeInstanceOf(DatabaseError);
    expect((error as DatabaseError).code).toBe("42501");
  });

  it("can read users", async () => {
    await expect(asApp("SELECT id, username, password_hash FROM users")).resolves.toBeDefined();
  });

  it("has no role attribute beyond LOGIN", async () => {
    const { rows } = await withClient(superuser(process.env, DATABASE), (client) =>
      client.query(
        `SELECT rolcanlogin, rolsuper, rolcreatedb, rolcreaterole, rolreplication, rolbypassrls
           FROM pg_roles WHERE rolname = 'synapse_app'`,
      ),
    );

    expect(rows).toEqual([
      {
        rolcanlogin: true,
        rolsuper: false,
        rolcreatedb: false,
        rolcreaterole: false,
        rolreplication: false,
        rolbypassrls: false,
      },
    ]);
  });

  it("gets DML on a table the owner creates later, through the default privileges", async () => {
    const privileges = await withClient(superuser(process.env, DATABASE), async (client) => {
      await client.query("BEGIN");
      try {
        await client.query("CREATE TABLE later (id int GENERATED BY DEFAULT AS IDENTITY)");
        const { rows } = await client.query(
          `SELECT has_table_privilege('synapse_app', 'later', 'SELECT, INSERT, UPDATE, DELETE')
                    AS dml,
                  has_table_privilege('synapse_app', 'later', 'TRUNCATE') AS truncate,
                  has_sequence_privilege('synapse_app', pg_get_serial_sequence('later', 'id'),
                                         'USAGE') AS sequence`,
        );
        return rows[0];
      } finally {
        await client.query("ROLLBACK");
      }
    });

    expect(privileges).toEqual({ dml: true, truncate: false, sequence: true });
  });

  it("leaves PUBLIC with no CONNECT or TEMP on the database and no CREATE on public", async () => {
    const { rows } = await withClient(superuser(process.env, DATABASE), (client) =>
      client.query(
        `SELECT has_database_privilege('public', current_database(), 'CONNECT') AS connect,
                has_database_privilege('public', current_database(), 'TEMP') AS temp,
                has_schema_privilege('public', 'public', 'CREATE') AS create,
                has_database_privilege('synapse_app', current_database(), 'CREATE, TEMP')
                  AS app_create_or_temp`,
      ),
    );

    expect(rows[0]).toEqual({
      connect: false,
      temp: false,
      create: false,
      app_create_or_temp: false,
    });
  });
});
